// 子模块 pin 的单一事实来源：直接读 gitlink（git ls-tree HEAD），不读 README、不手写。
// sync-submodule-pins.mjs 用它生成 README 区块；check-submodule-pins.mjs 用它校验。
// 2026-11-11 补：中英两份 README 都纳入生成/校验（此前只改中文，英文仍留 709cd64/bcdc62b）。
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const README = join(ROOT, 'README.md');
export const BEGIN = '<!-- SUBMODULE_PINS:BEGIN 由 scripts/sync-submodule-pins.mjs 自动生成，请勿手改 -->';
export const END = '<!-- SUBMODULE_PINS:END -->';

// 两份 README 用同一对 BEGIN/END 标记；文案按语言分别渲染。
export const TARGETS = [
  { file: 'README.md', lang: 'zh', anchor: '## 🔗 子模块锁定版本\n' },
  { file: 'README.en.md', lang: 'en', anchor: '## 🔗 Pinned submodule versions\n' },
];

const REPOS = {
  app: 'codecloud-dev/moxsh-terminal',
  site: 'codecloud-dev/mox-site',
};

export function readPins() {
  const out = execFileSync('git', ['ls-tree', 'HEAD', 'app', 'site'], { cwd: ROOT, encoding: 'utf8' });
  const pins = {};
  for (const line of out.trim().split('\n')) {
    // 160000 commit <sha>\t<path>
    const m = line.match(/^160000 commit ([0-9a-f]{40})\t(\S+)$/);
    if (m) pins[m[2]] = m[1];
  }
  const missing = Object.keys(REPOS).filter((k) => !pins[k]);
  if (missing.length) throw new Error(`gitlink 缺失：${missing.join(', ')}（子模块是否未提交？）`);
  return pins;
}

export function renderBlock(pins, lang = 'zh') {
  const rows = Object.entries(REPOS).map(([path, repo]) => {
    const sha = pins[path];
    const short = sha.slice(0, 7);
    const label = lang === 'en' ? 'view commit' : '查看该提交';
    return `| \`${path}\` | \`${repo}\` | \`${short}\`（[${label}](https://github.com/${repo}/tree/${sha})） |`;
  });
  const head = lang === 'en'
    ? [
        '| Submodule | Repo | Pinned commit (real gitlink) |',
        '| --- | --- | --- |',
      ]
    : [
        '| 子模块 | 仓库 | 锁定提交（真实 gitlink） |',
        '| --- | --- | --- |',
      ];
  const foot = lang === 'en'
    ? [
        '> Generated by `scripts/sync-submodule-pins.mjs` from `git ls-tree HEAD`; CI (`check-pins.yml`)',
        '> enforces this on every push / PR. Manual edits fail CI. After bumping a submodule, re-run',
        '> `node scripts/sync-submodule-pins.mjs` (both READMEs are updated together).',
      ]
    : [
        '> 本区块由 `scripts/sync-submodule-pins.mjs` 从 `git ls-tree HEAD` 生成，CI 由 `check-pins.yml` 校验；',
        '> 手动改这里会在下次 PR 直接失败。bump 子模块后请重跑 `node scripts/sync-submodule-pins.mjs`',
        '>（中英两份 README 会一起更新）。',
      ];
  return [BEGIN, ...head, ...rows, '', ...foot, END].join('\n');
}

// 传路径可校验任意一份 README；不传默认 README.md（兼容旧调用）。
export function readCurrentBlock(readmePath = README) {
  const text = readFileSync(readmePath, 'utf8');
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < 0 || b < a) return null;
  return text.slice(a, b + END.length);
}
